const assert=require('assert');
const core=require('../extension/gaze-core.js');
const sample=(x=.5,y=.5,blink=false)=>{
  const pts=Array.from({length:478},()=>({x:0,y:0}));
  pts[33]={x:.35,y:.42};pts[133]={x:.45,y:.42};pts[159]={x:.4,y:.40};pts[145]={x:.4,y:.44};
  pts[263]={x:.65,y:.42};pts[362]={x:.55,y:.42};pts[386]={x:.6,y:.40};pts[374]={x:.6,y:.44};
  for(let i=468;i<472;i++)pts[i]={x:.35+.1*x,y:.4+.04*y};
  for(let i=473;i<477;i++)pts[i]={x:.55+.1*x,y:.4+.04*y};
  const cats=[{categoryName:'eyeBlinkLeft',score:blink?.9:.04},{categoryName:'eyeBlinkRight',score:blink?.9:.04}];
  return core.sampleLandmarks(pts,cats);
};
assert.equal(core.sampleLandmarks([],[]),null);
assert.equal(core.POINTS.length,5);
assert.ok(Math.abs(sample().x-.5)<.02);
assert.ok(Math.abs(sample().y-.5)<.02);
assert.equal(sample(.5,.5,true).blink,true);
assert.equal(sample(.5,.5,false).blink,false);
const cal=core.calibrationFrom({center:{x:.5,y:.5},left:{x:.39,y:.5},right:{x:.61,y:.5},up:{x:.5,y:.35},down:{x:.5,y:.65}});
assert.ok(cal);
assert.ok(Math.abs(core.mapGaze({x:.5,y:.5},cal).x-.5)<.001);
assert.ok(core.mapGaze({x:.39,y:.5},cal).x<.3);
assert.ok(core.mapGaze({x:.61,y:.5},cal).x>.7);
assert.equal(core.calibrationFrom({center:{x:.5,y:.5}}),null);
assert.equal(core.calibrationFrom({center:{x:.5,y:.5},left:{x:.5,y:.5},right:{x:.5,y:.5},up:{x:.5,y:.5},down:{x:.5,y:.5}}),null);
let b=core.createBlinkMachine();
assert.deepEqual(b.update(false,100,true),[]);
assert.deepEqual(b.update(true,200,true),[]);
assert.deepEqual(b.update(false,320,true),[]);
assert.deepEqual(b.update(false,1100,true),['NEXT']);
b=core.createBlinkMachine();
assert.deepEqual(b.update(true,200,true),[]);
assert.deepEqual(b.update(false,300,true),[]);
assert.deepEqual(b.update(true,550,true),[]);
assert.deepEqual(b.update(false,670,true),['SELECT']);
assert.deepEqual(b.update(false,1800,true),[]);
b=core.createBlinkMachine();
b.update(true,200,true);b.update(false,300,true);
assert.deepEqual(b.update(false,1100,false),[]);
assert.deepEqual(b.update(false,1900,true),[]);
